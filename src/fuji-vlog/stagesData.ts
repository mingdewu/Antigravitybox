// 计算单个 Stage 的总帧数（30fps）
export const getStageFrames = (stage: FujiStageConfig, fps = 30): number => {
  return stage.shots.reduce((sum, shot) => sum + Math.round(shot.durationSec * fps), 0);
};

// 全片总帧数（36,000 帧 = 1200 秒 = 20分00秒）
export const FUJI_TOTAL_FRAMES = FUJI_STAGES_DATA.reduce(
  (sum, stage) => sum + getStageFrames(stage, 30),
  0
);
